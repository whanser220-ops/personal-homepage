import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { test } from "node:test";
import * as THREE from "three";
import { createWaterFields } from "../src/lib/home-scene/waterFields.js";

test("default water fields retain the original generated bytes and texture settings", () => {
  const fields = createWaterFields();
  const originalHashes = {
    waves: "ab9be2b3cdd5fa0550e091c0bc78b15aec2c5fcc8fee5f94b4982e1bb5c17983",
    flow: "7ad9e3afb918ab106a5fc2b142e40e6259a347eb3c9a5229e930a53d70713148",
    absorption: "3cd5820fbea8491ff8556d5e110a881d0107d8dfbd1916e39363d7d534ed629a",
  };
  try {
    for (const [name, hash] of Object.entries(originalHashes)) {
      assert.equal(createHash("sha256").update(fields[name].image.data).digest("hex"), hash, name);
      assert.equal(fields[name].minFilter, THREE.LinearFilter);
      assert.equal(fields[name].magFilter, THREE.LinearFilter);
      assert.equal(fields[name].version, 1);
    }
    assert.deepEqual([fields.waves.image.width, fields.waves.image.height], [192, 192]);
    assert.deepEqual([fields.flow.image.width, fields.flow.image.height], [64, 64]);
    assert.deepEqual([fields.absorption.image.width, fields.absorption.image.height], [128, 1]);
    assert.equal(fields.waves.wrapS, THREE.RepeatWrapping);
    assert.equal(fields.waves.wrapT, THREE.RepeatWrapping);
  } finally {
    fields.dispose();
  }
});

test("reuses deterministic generation for the same size while preserving independent texture ownership", context => {
  let calculations = 0;
  const hypot = Math.hypot;
  context.mock.method(Math, "hypot", (...values) => { calculations++; return hypot(...values); });
  const first = createWaterFields(11);
  const generated = calculations;
  const second = createWaterFields(11);
  try {
    assert.equal(generated, 11 * 11 * 34);
    assert.equal(calculations, generated, "same-size scene creation performs no wave simulation");
    for (const name of ["waves", "flow", "absorption"]) {
      assert.notEqual(first[name], second[name]);
      assert.notEqual(first[name].image.data, second[name].image.data);
      assert.deepEqual(first[name].image.data, second[name].image.data);
    }
    const original = second.waves.image.data[0];
    first.waves.image.data[0] ^= 255;
    assert.equal(second.waves.image.data[0], original);
    const third = createWaterFields(11);
    try {
      assert.equal(third.waves.image.data[0], original, "cached bytes cannot be changed through a texture instance");
      assert.equal(calculations, generated);
    } finally {
      third.dispose();
    }
  } finally {
    first.dispose();
    second.dispose();
  }
});

test("different requested sizes receive separately generated and cached fields", context => {
  let calculations = 0;
  const hypot = Math.hypot;
  context.mock.method(Math, "hypot", (...values) => { calculations++; return hypot(...values); });
  const first = createWaterFields(12);
  const other = createWaterFields(13);
  const repeat = createWaterFields(12);
  try {
    assert.equal(calculations, (12 * 12 + 13 * 13) * 34);
    assert.equal(first.waves.image.width, 12);
    assert.equal(other.waves.image.width, 13);
    assert.deepEqual(first.waves.image.data, repeat.waves.image.data);
  } finally {
    first.dispose();
    other.dispose();
    repeat.dispose();
  }
});

test("disposing one scene releases only its textures and leaves cached fields usable", () => {
  const first = createWaterFields(14);
  const second = createWaterFields(14);
  let firstDisposals = 0, secondDisposals = 0;
  for (const texture of Object.values(first)) {
    if (texture.isTexture) texture.addEventListener("dispose", () => firstDisposals++);
  }
  for (const texture of Object.values(second)) {
    if (texture.isTexture) texture.addEventListener("dispose", () => secondDisposals++);
  }
  first.dispose();
  assert.equal(firstDisposals, 3);
  assert.equal(secondDisposals, 0);
  const third = createWaterFields(14);
  assert.deepEqual(second.waves.image.data, third.waves.image.data);
  second.dispose();
  third.dispose();
  assert.equal(secondDisposals, 3);
});
